const savedLanguage = typeof localStorage !== 'undefined' ? localStorage.getItem('it25-language') : null

void i18n.use(initReactI18next).init({
  resources: {
    az: { translation: az },
    en: { translation: en },
  },
  lng: savedLanguage && ['az', 'en'].includes(savedLanguage) ? savedLanguage : 'az',
  fallbackLng: 'az',
  interpolation: { escapeValue: false },
})

export function setLanguage(language: 'az' | 'en'): void {
  localStorage.setItem('it25-language', language)
  void i18n.changeLanguage(language)
}

export default i18n
